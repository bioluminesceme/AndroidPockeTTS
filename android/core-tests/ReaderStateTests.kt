package nl.user.pockettest

import java.nio.file.Files

fun runReaderStateTests() {
    check(SentenceSelection.offsetInSentence("First.\nA long wrapped sentence.", 0) == 0)
    check(SentenceSelection.offsetInSentence("First.\nA long wrapped sentence.", 7) == 0)
    check(SentenceSelection.offsetInSentence("First.\nA long wrapped sentence.", 14) == 7)
    check(SentenceSelection.offsetInSentence("Café 😀.\nNext sentence.", "Café 😀.\nNext ".length) == 5)
    check(SentenceSelection.offsetInSentence("First.\n", 999) == 0)
    check(SentenceSelection.offsetInSentence("", -1) == 0)
    val timeline = SentenceTimeline()
    timeline.start(12, 0)
    timeline.finish(12, 100)
    timeline.start(13, 100)
    timeline.finish(13, 200)
    check(timeline.audible(0) == null)
    check(timeline.audible(1)?.line == 12)
    check(timeline.audible(100)?.line == 12)
    check(timeline.audible(101)?.line == 13)
    check(timeline.audible(200)?.end == 200L)
    val timer = SentenceTimer()
    timer.set(1, 100)
    check(!timer.observe(1099, 12))
    check(timer.holdFuture(1000, 0, 24000, 24000))
    check(timer.observe(1100, 12))
    check(timer.targetLine == 12)
    check(!timer.observe(1200, 13) && timer.targetLine == 12)
    timer.set(0, 1200)
    check(!timer.expired && timer.deadline == null)
    timer.set(1, 0)
    check(timer.observe(1000, null) && timer.targetLine == -1)
    timer.set(20, 0)
    check(!timer.holdFuture(0, 0, 24000, 24000))
    check(!timer.holdFuture(19999, 24000, 24000, 24000))
    check(timer.observe(20000, 10))
    timer.retarget()
    check(timer.deadline == 20000L && !timer.expired && timer.targetLine == null)
    val defaults = SentenceTimer()
    check(!defaults.startDefault(0, 0) && defaults.deadline == null)
    check(defaults.startDefault(30, 1000) && defaults.deadline == 1_801_000L)
    check(!defaults.startDefault(15, 2000) && defaults.deadline == 1_801_000L)
    check(defaults.startDefault(15, 1_801_000) && defaults.deadline == 2_701_000L)
    check(defaults.observe(2_701_000, 5) && defaults.startDefault(15, 2_701_000) && !defaults.expired && defaults.targetLine == null)
    check(timer.observe(20001, 22) && timer.targetLine == 22)
    val path = Files.createTempFile("reader-window", ".txt")
    try {
        path.toFile().writeText("Café first.\nSecond sentence.\nThird sentence.\n", Charsets.UTF_8)
        val document = ReaderDocument(path.toFile())
        val window = document.window(1)
        check(window.text.substring(window.activeStart, window.activeEnd) == "Second sentence.")
        check(document.window(2).text.substring(document.window(2).activeStart).startsWith("Third sentence."))
        check(document.window(3).text.isEmpty())
        check(document.percent(0) == 0.0 && document.percent(3) == 100.0)
        check(document.totalWords == 6L && document.totalSeconds(1f) == 2L)
        check(document.elapsedSeconds(-5, 1f) == 0L && document.elapsedSeconds(2, 1f) == 1L)
        check(document.elapsedSeconds(3, 0.5f) == 4L && document.elapsedSeconds(999, 1f) == 2L)
        check(ReaderDocument.formatEstimate(59) == "0m" && ReaderDocument.formatEstimate(754) == "12m")
        check(ReaderDocument.formatEstimate(3900) == "1h 05m" && ReaderDocument.formatEstimate(33000) == "9h 10m")
        check(ReaderDocument.formatEstimate(-5) == "0m")
        check(window.firstLine == 0)
        check(SentenceSelection.lineAt(window.text, window.firstLine, window.activeStart) == 1)
        check(SentenceSelection.lineAt("First.\nSecond.\n", 50, 8) == 51)
        check(SentenceSelection.lineAt("First.\nSecond.\n", 50, 7) == 51)
        check(SentenceSelection.lineAt("First.\nSecond.\n", 50, 6) == 50)
        check(SentenceSelection.lineAt("First.\nSecond.\n", 50, 1000) == 51)
        check(SentenceSelection.lineAt("", 50, 0) == 50)
        check(SentenceSelection.lineAt("First.\nSecond.\n", 50, -1) == 50)
        check(SentenceSelection.contentOffset("\uFEFFCafé \n first.", 9) == 5)
        check(document.lineForContentOffset(0) == 0)
        check(document.lineForContentOffset("Caféfirst.".length) == 1)
        check(document.lineForContentOffset(9999) == 2)
        check(SentenceSelection.lineAt("Emoji 😀.\nCafé next.\n", 7, "Emoji 😀.\n".length) == 8)
        check(SentenceSelection.contentOffset("Emoji 😀.\nCafé next.", "Emoji 😀.\n".length) == "Emoji😀.".length)
        path.toFile().writeText((0..30).joinToString("\n") { "Sentence $it." } + "\n", Charsets.UTF_8)
        val later = ReaderDocument(path.toFile()).window(20)
        check(later.firstLine == 18)
        check(SentenceSelection.lineAt(later.text, later.firstLine, later.activeStart) == 20)
        path.toFile().writeText((0..200).joinToString("\n") { "Sentence $it has six separate words." } + "\n", Charsets.UTF_8)
        val longBook = ReaderDocument(path.toFile())
        check(longBook.lineCount == 201)
        check(longBook.seekSeconds(50, 60, 1f) == 80)
        check(longBook.seekSeconds(50, -60, 1f) == 20)
        check(longBook.seekSeconds(50, 60, 1.5f) == 95)
        check(longBook.seekSeconds(5, -60, 1f) == 0)
        check(longBook.seekSeconds(190, 60, 1f) == 200)
        check(longBook.seekSeconds(200, 60, 1f) == 200)
        check(longBook.seekSeconds(0, -60, 1f) == 0)
        check(longBook.seekSeconds(50, 0, 1f) == 50)
        val browsing = longBook.browseWindow(100)
        check(browsing.firstLine == 60)
        check(SentenceSelection.lineAt(browsing.text, browsing.firstLine, browsing.activeStart) == 100)
        check(browsing.text.contains("Sentence 179"))
        path.toFile().writeText("A very long sentence " + "word ".repeat(400) + ".\nNext.\n", Charsets.UTF_8)
        check(ReaderDocument(path.toFile()).seekSeconds(0, 60, 1f) == 1)
    } finally { check(path.toFile().delete()) }
    val directory = Files.createTempDirectory("book-positions").toFile()
    try {
        val first = java.io.File(directory, "selected-book.txt").apply { writeText("First book.\n", Charsets.UTF_8) }
        val second = java.io.File(directory, "playback-input.txt").apply { writeText("Second book.\n", Charsets.UTF_8) }
        val firstKey = BookPositions.key(first)
        val secondKey = BookPositions.key(second)
        check(BookPositions.load(directory, firstKey) == null)
        BookPositions.save(directory, firstKey, first.name, 27)
        BookPositions.save(directory, secondKey, second.name, 81)
        check(BookPositions.load(directory, firstKey) == 27)
        check(BookPositions.load(directory, secondKey) == 81)
        BookPositions.save(directory, firstKey, first.name, 28)
        check(BookPositions.load(directory, firstKey) == 28)
        check(BookPositions.load(directory, secondKey) == 81)
        second.writeText(first.readText(Charsets.UTF_8), Charsets.UTF_8)
        check(BookPositions.key(second) == firstKey)
        check(BookPositions.load(directory, BookPositions.key(second)) == 28)
        second.writeText("Changed book.\n", Charsets.UTF_8)
        check(BookPositions.load(directory, BookPositions.key(second)) == null)
        val stored = java.io.File(directory, "book-positions.properties").readText(Charsets.UTF_8)
        check(stored.contains("selected-book.txt") && stored.contains("playback-input.txt"))
        check(!java.io.File(directory, "book-positions.pending").exists())
        val reopened = java.io.File(directory.absolutePath)
        check(BookPositions.load(reopened, firstKey) == 28)
        check(runCatching { BookPositions.save(directory, firstKey, first.name, -1) }.isFailure)
    } finally { check(directory.deleteRecursively()) }
    println("PASS: Estimated minute seeking, speed scaling, scroll windows, and persistent separate book positions")
    println("PASS: Audible sample boundaries, timer expiry and cancellation, future-sentence guard, and UTF-8 text windows")
}
